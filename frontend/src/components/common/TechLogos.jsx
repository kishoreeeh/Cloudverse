// Dynamic Technology Logo Loader Component
export default function TechIcon({ slug, className = "w-6 h-6" }) {
  const normalized = (slug || '').toLowerCase();
  if (normalized.includes('aws')) return <AwsLogo className={className} />;
  if (normalized.includes('docker')) return <DockerLogo className={className} />;
  if (normalized.includes('k8s') || normalized.includes('kubernetes')) return <K8sLogo className={className} />;
  if (normalized.includes('linux')) return <LinuxLogo className={className} />;
  if (normalized.includes('git')) return <GitLogo className={className} />;
  if (normalized.includes('terraform')) return <TerraformLogo className={className} />;
  return <CloudVerseLogo className={className} />;
}
